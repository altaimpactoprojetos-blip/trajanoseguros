-- Trajano Seguros — solicitações de cotação enviadas pelo site
-- Projeto Supabase: CRM Vitalício (lffzxqwgqgsiumunahyt)
-- Este arquivo reúne, na ordem, tudo que foi aplicado no banco.
--
-- Segurança:
--   * O site (chave pública) NÃO acessa a tabela: só chama a função trajano_solicitar_cotacao,
--     que valida tudo no servidor, limita abusos e devolve apenas o número do protocolo.
--   * Só usuários logados cadastrados em trajano_cotacoes_admins leem e atualizam as cotações.

-- 1. Tabelas
create table if not exists public.trajano_cotacoes (
  id uuid primary key default gen_random_uuid(),
  protocolo integer generated by default as identity unique,
  tipo text not null check (tipo in ('Auto', 'Residencial', 'Vida', 'Empresarial')),
  nome text not null check (char_length(nome) between 3 and 120),
  telefone text not null check (telefone ~ '^[0-9]{10,11}$'),
  email text check (email is null or (char_length(email) <= 160 and email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$')),
  detalhes jsonb not null default '{}'::jsonb check (jsonb_typeof(detalhes) = 'object' and pg_column_size(detalhes) <= 2000),
  observacoes text check (observacoes is null or char_length(observacoes) <= 1000),
  ciente_privacidade_em timestamptz not null,
  aviso_privacidade_versao text not null check (char_length(aviso_privacidade_versao) <= 20),
  pagina text check (pagina is null or char_length(pagina) <= 200),
  status text not null default 'nova' check (status in ('nova', 'em_atendimento', 'proposta_enviada', 'fechada', 'arquivada')),
  notas_internas text check (notas_internas is null or char_length(notas_internas) <= 4000),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create index if not exists trajano_cotacoes_criado_em_idx on public.trajano_cotacoes (criado_em desc);
create index if not exists trajano_cotacoes_telefone_idx on public.trajano_cotacoes (telefone, criado_em desc);

create table if not exists public.trajano_cotacoes_admins (
  email text primary key check (email = lower(email))
);

-- 2. Quem pode ver o painel
create or replace function public.trajano_eh_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.trajano_cotacoes_admins
    where email = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;
revoke all on function public.trajano_eh_admin() from public, anon;
grant execute on function public.trajano_eh_admin() to authenticated;

-- 3. RLS: nada para anon; admins leem e atualizam status/notas
alter table public.trajano_cotacoes enable row level security;
alter table public.trajano_cotacoes_admins enable row level security;

revoke all on public.trajano_cotacoes from anon, authenticated;
revoke all on public.trajano_cotacoes_admins from anon, authenticated;
grant select on public.trajano_cotacoes to authenticated;
grant update (status, notas_internas) on public.trajano_cotacoes to authenticated;
grant select, insert, update, delete on public.trajano_cotacoes to service_role;
grant select, insert, update, delete on public.trajano_cotacoes_admins to service_role;

drop policy if exists "admins_leem_cotacoes" on public.trajano_cotacoes;
create policy "admins_leem_cotacoes" on public.trajano_cotacoes
  for select to authenticated using (public.trajano_eh_admin());
drop policy if exists "admins_atualizam_cotacoes" on public.trajano_cotacoes;
create policy "admins_atualizam_cotacoes" on public.trajano_cotacoes
  for update to authenticated using (public.trajano_eh_admin()) with check (public.trajano_eh_admin());

create or replace function public.trajano_cotacoes_atualizado_em()
returns trigger language plpgsql set search_path = public as $$
begin
  new.atualizado_em := now();
  return new;
end;
$$;
drop trigger if exists trg_trajano_cotacoes_atualizado_em on public.trajano_cotacoes;
create trigger trg_trajano_cotacoes_atualizado_em
  before update on public.trajano_cotacoes
  for each row execute function public.trajano_cotacoes_atualizado_em();

-- 4. Função chamada pelo formulário do site
create or replace function public.trajano_solicitar_cotacao(
  p_tipo text,
  p_nome text,
  p_telefone text,
  p_detalhes jsonb,
  p_ciente_privacidade boolean,
  p_aviso_versao text,
  p_email text default null,
  p_observacoes text default null,
  p_pagina text default null
) returns json
language plpgsql security definer set search_path = public as $$
declare
  v_tel text := regexp_replace(coalesce(p_telefone, ''), '\D', '', 'g');
  v_nome text := btrim(regexp_replace(coalesce(p_nome, ''), '\s+', ' ', 'g'));
  v_email text := lower(nullif(btrim(coalesce(p_email, '')), ''));
  v_obs text := nullif(btrim(coalesce(p_observacoes, '')), '');
  v_det jsonb := '{}'::jsonb;
  v_chave text;
  v_valor text;
  v_ano int;
  v_existente int;
  v_protocolo int;
  v_permitidas text[];
  v_obrigatorias text[];
begin
  if p_ciente_privacidade is distinct from true then
    raise exception 'privacidade' using errcode = 'P0001', hint = 'Confirme a leitura do aviso de privacidade.';
  end if;
  if p_tipo is null or p_tipo not in ('Auto', 'Residencial', 'Vida', 'Empresarial') then
    raise exception 'tipo' using errcode = 'P0001', hint = 'Tipo de seguro inválido.';
  end if;
  if char_length(v_nome) < 3 or char_length(v_nome) > 120 then
    raise exception 'nome' using errcode = 'P0001', hint = 'Informe seu nome.';
  end if;
  if v_tel ~ '^55[0-9]{10,11}$' then
    v_tel := substr(v_tel, 3);
  end if;
  if v_tel !~ '^[1-9][0-9][0-9]{8,9}$' then
    raise exception 'telefone' using errcode = 'P0001', hint = 'Informe um telefone com DDD.';
  end if;
  if v_email is not null and (char_length(v_email) > 160 or v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$') then
    raise exception 'email' using errcode = 'P0001', hint = 'E-mail inválido.';
  end if;
  if v_obs is not null and char_length(v_obs) > 1000 then
    raise exception 'observacoes' using errcode = 'P0001', hint = 'Observações muito longas.';
  end if;

  -- Só os campos previstos para cada produto são guardados (coleta mínima)
  case p_tipo
    when 'Auto' then v_permitidas := array['veiculo', 'ano', 'uso', 'cep']; v_obrigatorias := array['veiculo', 'ano'];
    when 'Residencial' then v_permitidas := array['imovel', 'ocupacao', 'cidade']; v_obrigatorias := array['imovel', 'ocupacao'];
    when 'Vida' then v_permitidas := array['idade', 'profissao']; v_obrigatorias := array['idade'];
    when 'Empresarial' then v_permitidas := array['atividade', 'cidade']; v_obrigatorias := array['atividade'];
  end case;
  if p_detalhes is not null and jsonb_typeof(p_detalhes) = 'object' then
    for v_chave, v_valor in select key, btrim(value) from jsonb_each_text(p_detalhes) loop
      if v_chave = any(v_permitidas) and v_valor <> '' then
        if char_length(v_valor) > 120 then
          raise exception '%', v_chave using errcode = 'P0001', hint = 'Campo muito longo.';
        end if;
        v_det := v_det || jsonb_build_object(v_chave, v_valor);
      end if;
    end loop;
  end if;
  foreach v_chave in array v_obrigatorias loop
    if not v_det ? v_chave then
      raise exception '%', v_chave using errcode = 'P0001', hint = 'Campo obrigatório.';
    end if;
  end loop;
  if v_det ? 'ano' then
    v_ano := case when v_det ->> 'ano' ~ '^[0-9]{4}$' then (v_det ->> 'ano')::int end;
    if v_ano is null or v_ano < 1950 or v_ano > extract(year from now())::int + 1 then
      raise exception 'ano' using errcode = 'P0001', hint = 'Ano do veículo inválido.';
    end if;
  end if;
  if v_det ? 'idade' and (v_det ->> 'idade' !~ '^[0-9]{1,3}$' or (v_det ->> 'idade')::int not between 18 and 100) then
    raise exception 'idade' using errcode = 'P0001', hint = 'Idade inválida.';
  end if;
  if v_det ? 'cep' and v_det ->> 'cep' !~ '^[0-9]{5}-?[0-9]{3}$' then
    raise exception 'cep' using errcode = 'P0001', hint = 'CEP inválido.';
  end if;

  -- Envio repetido (duplo clique, recarregar a página): devolve o mesmo protocolo
  select protocolo into v_existente from public.trajano_cotacoes
   where telefone = v_tel and tipo = p_tipo and criado_em > now() - interval '10 minutes'
   order by criado_em desc limit 1;
  if v_existente is not null then
    return json_build_object('protocolo', v_existente, 'repetido', true);
  end if;

  -- Limites contra abuso
  if (select count(*) from public.trajano_cotacoes where telefone = v_tel and criado_em > now() - interval '1 day') >= 5 then
    raise exception 'limite' using errcode = 'P0001', hint = 'Muitas solicitações para este telefone. Tente novamente amanhã.';
  end if;
  if (select count(*) from public.trajano_cotacoes where criado_em > now() - interval '10 minutes') >= 30 then
    raise exception 'limite' using errcode = 'P0001', hint = 'Muitas solicitações no momento. Tente novamente em alguns minutos.';
  end if;

  insert into public.trajano_cotacoes
    (tipo, nome, telefone, email, detalhes, observacoes, ciente_privacidade_em, aviso_privacidade_versao, pagina)
  values
    (p_tipo, v_nome, v_tel, v_email, v_det, v_obs, now(), left(coalesce(p_aviso_versao, '?'), 20), left(p_pagina, 200))
  returning protocolo into v_protocolo;

  return json_build_object('protocolo', v_protocolo, 'repetido', false);
end;
$$;
revoke all on function public.trajano_solicitar_cotacao(text, text, text, jsonb, boolean, text, text, text, text) from public;
grant execute on function public.trajano_solicitar_cotacao(text, text, text, jsonb, boolean, text, text, text, text) to anon, authenticated;
revoke all on function public.trajano_cotacoes_atualizado_em() from public, anon, authenticated;

